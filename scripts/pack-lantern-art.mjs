/** Pack the generated sources as palette-locked, origin-clean data URLs for the SDK's opaque-origin iframe. */
import { readFile, writeFile } from "node:fs/promises";
import { chromium } from "playwright";

const root = new URL("../game/assets/lantern/", import.meta.url);
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const exports = [];
  for (const [name, source] of [["characterUrl", "characters-source.png"], ["terrainUrl", "terrain-source.png"]]) {
    const input = `data:image/png;base64,${(await readFile(new URL(source, root))).toString("base64")}`;
    const packed = await page.evaluate(async url => {
      const img = new Image(); img.src = url; await img.decode();
      const canvas = document.createElement("canvas"); canvas.width = img.width; canvas.height = img.height;
      const ctx = canvas.getContext("2d"); ctx.drawImage(img, 0, 0);
      const data = ctx.getImageData(0, 0, canvas.width, canvas.height), px = data.data;
      const palette = [[24, 44, 36], [219, 231, 173], [166, 186, 118], [97, 123, 82]];
      for (let i = 0; i < px.length; i += 4) {
        let best = Infinity, nearest = palette[0];
        for (const color of palette) {
          const distance = color.reduce((sum, channel, n) => sum + (px[i + n] - channel) ** 2, 0);
          if (distance < best) { best = distance; nearest = color; }
        }
        [px[i], px[i + 1], px[i + 2]] = nearest;
      }
      ctx.putImageData(data, 0, 0);
      return canvas.toDataURL("image/png");
    }, input);
    exports.push(`export const ${name} = ${JSON.stringify(packed)};`);
    console.log(`${source}: ${Math.round(packed.length / 1024)} KiB packed`);
  }
  await writeFile(new URL("packed.ts", root), "// Generated by npm run art:pack. Sources and prompts are alongside this file.\n" + exports.join("\n") + "\n");
} finally { await browser.close(); }
