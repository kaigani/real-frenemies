const masks = new Map<string, number[]>();
for (const [ch, rows] of Object.entries(ROWS)) {
  if (rows.length !== 7 || rows.some(r => r.length !== 5)) throw new Error(`Bad display glyph ${ch}`);
  masks.set(ch, rows.map(r => [...r].reduce((m, c, i) => c === "#" ? m | (1 << i) : m, 0)));
}

export const BIG_W = 6;
export const BIG_H = 7;

export function bigGlyph(ch: string) {
  return masks.get(ch.toUpperCase()) ?? masks.get(" ")!;
}

export function bigWidth(text: string) {
  return text.length ? text.length * BIG_W - 1 : 0;
}
